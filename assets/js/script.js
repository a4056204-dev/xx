function getUsedCodes() {
    const usedCodesJson = localStorage.getItem('usedInviteCodes');
    return usedCodesJson ? JSON.parse(usedCodesJson) : [];
}

function saveUsedCode(code) {
    const usedCodes = getUsedCodes();
    if (!usedCodes.includes(code)) {
        usedCodes.push(code);
        localStorage.setItem('usedInviteCodes', JSON.stringify(usedCodes));
    }
}

function validateInviteCode() {
    if (!inviteCodeInput || !inviteMessage || !validateInviteBtn || !downloadFreeBtn) {
        return false;
    }
    
    const code = inviteCodeInput.value.trim().toUpperCase();
    
    if (!code) {
        inviteMessage.textContent = currentLang === 'pt' ? 'Por favor, insira um código' : 'Please enter a code';
        inviteMessage.className = 'invite-code-message error';
        return false;
    }
    
    const usedCodes = getUsedCodes();
    if (usedCodes.includes(code)) {
        inviteMessage.textContent = currentLang === 'pt' 
            ? '✗ Este código já foi usado. Cada código só pode ser usado uma vez.' 
            : '✗ This code has already been used. Each code can only be used once.';
        inviteMessage.className = 'invite-code-message error';
        return false;
    }
    
    if (validInviteCodes.includes(code)) {
        inviteCodeValidated = true;
        inviteMessage.textContent = currentLang === 'pt' 
            ? '✓ Código válido! Acesso liberado por 30 dias.' 
            : '✓ Valid code! Access granted for 30 days.';
        inviteMessage.className = 'invite-code-message success';
        
        inviteCodeInput.disabled = true;
        validateInviteBtn.disabled = true;
        
        downloadFreeBtn.disabled = false;
        
        saveUsedCode(code);
        
        const expiryDate = new Date();
        expiryDate.setDate(expiryDate.getDate() + 30);
        localStorage.setItem('inviteCodeValidated', 'true');
        localStorage.setItem('inviteCodeExpiry', expiryDate.getTime().toString());
        localStorage.setItem('inviteCode', code);
        
        return true;
    } else {
        inviteMessage.textContent = currentLang === 'pt' 
            ? '✗ Código inválido. Tente novamente.' 
            : '✗ Invalid code. Please try again.';
        inviteMessage.className = 'invite-code-message error';
        return false;
    }
}

function checkStoredInviteCode() {
    if (!inviteCodeInput || !validateInviteBtn || !downloadFreeBtn || !inviteMessage) {
        return;
    }
    
    const validated = localStorage.getItem('inviteCodeValidated') === 'true';
    const expiry = localStorage.getItem('inviteCodeExpiry');
    const savedCode = localStorage.getItem('inviteCode');
    
    if (validated && expiry && savedCode) {
        const expiryDate = new Date(parseInt(expiry));
        const now = new Date();
        
        if (now < expiryDate) {
            inviteCodeValidated = true;
            inviteCodeInput.value = savedCode;
            inviteCodeInput.disabled = true;
            validateInviteBtn.disabled = true;
            downloadFreeBtn.disabled = false;
            inviteMessage.textContent = currentLang === 'pt' 
                ? '✓ Código válido! Acesso liberado por 30 dias.' 
                : '✓ Valid code! Access granted for 30 days.';
            inviteMessage.className = 'invite-code-message success';
        } else {
            localStorage.removeItem('inviteCodeValidated');
            localStorage.removeItem('inviteCodeExpiry');
            localStorage.removeItem('inviteCode');
            inviteCodeValidated = false;
            downloadFreeBtn.disabled = true;
        }
    } else {
        inviteCodeValidated = false;
        downloadFreeBtn.disabled = true;
    }
}

